import { defineConfig } from 'orval';

/** Generates only the operations Realtime is authorized to call. */
function internalRoutes(service: string, operationIds: string[]) {
  const specification = `node_modules/@cadenway/contracts/specs/openapi/internal/${service}.yaml`;
  return {
    input: { target: specification, filters: { operationIds } },
    output: {
      client: 'fetch' as const,
      mode: 'single' as const,
      target: `src/clients/generated/${service}.ts`,
      override: {
        header: (): string[] => [
          `Generated by Orval from ${specification}.`,
          'Do not edit: run `pnpm generate:clients`.',
        ],
        fetch: { httpClientInjection: 'factory' as const, includeHttpResponseReturnType: true },
      },
    },
  };
}

export default defineConfig({
  'identity-service': internalRoutes('identity-service', ['redeemRealtimeTicketInternal']),
  'task-service': internalRoutes('task-service', [
    'checkListAccessInternal',
    'checkTaskAccessInternal',
  ]),
});
